/**
 * Generate sw.js with a precache list and a content hash.
 *
 * Run from the game folder:  node tools/build-sw.mjs
 *
 * The precache list is generated rather than hand-written because it is well
 * over a hundred paths once the three.js addons are counted, and a
 * hand-maintained list is a list that silently goes stale. The cache NAME is
 * the content hash, so a changed file means a new cache and the activate
 * handler deletes every older one - there is no per-URL cache busting to get
 * wrong anywhere.
 *
 * Re-run this whenever any shipped file changes.
 */

import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/**
 * What to precache.
 *
 * The Draco and Basis decoders are deliberately EXCLUDED: together they are
 * 1.3 MB, they are fetched lazily and only if a compressed asset is actually
 * loaded, and precaching them would add a second and a half to a first visit
 * on a phone for files most players never touch.
 */
const INCLUDE = [/\.html$/, /\.css$/, /\.js$/, /\.woff2$/, /\.png$/, /\.webmanifest$/];
const EXCLUDE = [
  /^tools\//,
  /^sw\.js$/,
  /\/libs\/draco\//,
  /\/libs\/basis\//,
  /LICENSE/,
];

function walk(dir, base = "") {
  const out = [];
  for (const entry of fs.readdirSync(path.join(ROOT, dir || "."), { withFileTypes: true })) {
    const rel = base ? `${base}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...walk(path.join(dir, entry.name), rel));
    else out.push(rel);
  }
  return out;
}

const files = walk("")
  .filter((f) => INCLUDE.some((re) => re.test(f)))
  .filter((f) => !EXCLUDE.some((re) => re.test(f)))
  .sort();

const hash = crypto.createHash("sha1");
for (const f of files) hash.update(f).update(fs.readFileSync(path.join(ROOT, f)));
const version = `withroom-${hash.digest("hex").slice(0, 10)}`;

const precache = ["./", ...files];

const sw = `/*
 * Service worker for WITHROOM.
 *
 * GENERATED by tools/build-sw.mjs - do not edit by hand. Re-run that script
 * after changing any shipped file, or returning players will keep the old
 * build until their cache is cleared.
 */
const VERSION = ${JSON.stringify(version)};

const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener("install", (e) => {
  e.waitUntil(
    caches
      .open(VERSION)
      // \`cache: "reload"\` bypasses the HTTP cache while precaching, so a
      // stale copy from a CDN or the browser cache cannot be baked into the
      // new version the moment it is created.
      .then((c) => c.addAll(PRECACHE.map((u) => new Request(u, { cache: "reload" }))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((k) => k !== VERSION).map((k) => caches.delete(k))),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (e) => {
  const url = new URL(e.request.url);
  // Never intercept another origin or a non-GET. The game makes no network
  // calls of its own, but the page embedding it might.
  if (e.request.method !== "GET" || url.origin !== location.origin) return;

  // Navigations are network-first, so a new build is picked up on the next
  // visit rather than on the one after it.
  if (e.request.mode === "navigate") {
    e.respondWith(
      fetch(e.request)
        .then((res) => {
          const copy = res.clone();
          caches.open(VERSION).then((c) => c.put(e.request, copy));
          return res;
        })
        .catch(() =>
          caches.match(e.request).then((hit) => hit || caches.match("./index.html")),
        ),
    );
    return;
  }

  // Everything else is cache-first: these files are immutable within a
  // version, and the version changes whenever any of them does.
  e.respondWith(
    caches.match(e.request).then(
      (hit) =>
        hit ||
        fetch(e.request).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(VERSION).then((c) => c.put(e.request, copy));
          }
          return res;
        }),
    ),
  );
});
`;

fs.writeFileSync(path.join(ROOT, "sw.js"), sw);

let bytes = 0;
for (const f of files) bytes += fs.statSync(path.join(ROOT, f)).size;
console.log(`sw.js written`);
console.log(`  version   ${version}`);
console.log(`  precache  ${files.length} files, ${(bytes / 1024 / 1024).toFixed(2)} MB`);
